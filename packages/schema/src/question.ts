/**
 * Unified question bank schema shared by every event. See docs/DESIGN.md §4.
 */

import type { Division } from "./event.ts";

export type License =
  | "original" // written or generated by us — we own it
  | "licensed" // used with explicit permission from the author/tournament
  | "cc-by-nc-sa" // e.g. Scioly.org wiki-derived (confirm exact version)
  | "link-only"; // metadata only; content lives elsewhere

export type Provenance =
  | { source: "original"; authorId: string }
  | {
      source: "template";
      templateId: string;
      templateVersion: string;
      /** Seed makes generated items reproducible and re-gradable. */
      seed: number;
    }
  | {
      source: "llm";
      model: string;
      promptVersion: string;
      /** IDs of content blocks the generation was grounded in. */
      groundedIn: string[];
    }
  | {
      source: "licensed-test";
      tournament: string;
      year: number;
      authors: string[];
      agreementId: string;
      questionNumber?: string;
    }
  | {
      source: "wiki";
      pageTitle: string;
      revisionId: number;
      retrievedAt: string;
    };

export type ReviewStatus =
  | "draft"
  | "auto-verified" // passed automated checks (blind re-solve, numeric recompute)
  | "human-verified" // approved by a reviewer — eligible for mock tests
  | "flagged"
  | "retired";

export interface Review {
  status: ReviewStatus;
  reviewerIds?: string[];
  reports?: { userId: string; reason: string; at: string }[];
}

export interface Media {
  kind: "image" | "diagram" | "data-file" | "pdb" | "audio";
  url: string;
  alt: string;
  credit?: string;
  license: License;
}

interface QuestionBase {
  id: string;
  eventSlug: string;
  divisions: Division[];
  /** Rule seasons this question is valid for. */
  seasons: number[];
  /** Topic IDs from content/events/<slug>/topics.yaml. */
  topics: string[];
  difficulty: 1 | 2 | 3 | 4 | 5;
  prompt: string; // Markdown + KaTeX
  media?: Media[];
  solution?: { steps: string[]; explanation?: string };
  points?: number;
  license: License;
  provenance: Provenance;
  review: Review;
}

export interface McqQuestion extends QuestionBase {
  type: "mcq" | "multi-select";
  choices: { id: string; text: string; media?: Media }[];
  correct: string[];
}

export interface NumericQuestion extends QuestionBase {
  type: "numeric";
  answer: number;
  /** Relative tolerance, e.g. 0.02 for ±2%. */
  relTolerance: number;
  units?: string;
  sigFigs?: number;
}

export interface ShortAnswerQuestion extends QuestionBase {
  type: "short-answer";
  accepted: string[];
  /** Allow minor misspellings (Levenshtein-based). */
  fuzzy: boolean;
}

export interface FreeResponseQuestion extends QuestionBase {
  type: "free-response";
  rubric: { criterion: string; points: number }[];
  sampleAnswer?: string;
}

export interface ImageIdQuestion extends QuestionBase {
  type: "image-id";
  media: Media[];
  accepted: string[];
  /** e.g. "species", "mineral", "deep-sky object" */
  idLevel?: string;
}

export interface MatchingQuestion extends QuestionBase {
  type: "matching";
  left: string[];
  right: string[];
  /** Index pairs [leftIdx, rightIdx]. */
  pairs: [number, number][];
}

export interface OrderingQuestion extends QuestionBase {
  type: "ordering";
  items: string[];
  /** Correct order as indices into `items`. */
  order: number[];
}

export interface CipherQuestion extends QuestionBase {
  type: "cipher";
  cipher: string; // e.g. "aristocrat", "patristocrat", "hill-2x2", "baconian"
  ciphertext: string;
  plaintext: string;
  hint?: string;
  /** Errors allowed before points are deducted (per the season's scoring rules). */
  freeErrors?: number;
}

export interface DataTableQuestion extends QuestionBase {
  type: "data-table";
  table: { headers: string[]; rows: (string | number | null)[][] };
  /** Cells to fill: [row, col] → accepted value. */
  blanks: { row: number; col: number; answer: number | string; relTolerance?: number }[];
}

export type Question =
  | McqQuestion
  | NumericQuestion
  | ShortAnswerQuestion
  | FreeResponseQuestion
  | ImageIdQuestion
  | MatchingQuestion
  | OrderingQuestion
  | CipherQuestion
  | DataTableQuestion;

/** Only human-verified questions may appear in timed mock tests. */
export function isMockTestEligible(q: Question): boolean {
  return q.review.status === "human-verified";
}
